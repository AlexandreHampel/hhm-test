import { APIResponse } from '@playwright/test';
import { test, expect, VISIT_API_TAGS } from '../../../../fixtures/api.fixture';
import { expectStatus, readJson } from '../../helpers/http';
import { SAME_REQUEST_TOLERANCE_MS, toEpoch } from '../../helpers/time';
import { referenceId } from '../../helpers/references';
import { expectActiveVisit, expectApiError, expectVisitContract, expectVisitToMatchPayload, idsOf } from '../../assertions/visits';
import { buildRequiredOnlyVisit, buildVisit, buildVisitWithout, MALFORMED_IDS, UNKNOWN_OBJECT_ID } from '../../payloads/visit';
import { Person, Role } from '../../helpers/models/person';
import { VISIT_TYPES, Visit, VisitPayload } from '../../helpers/models/visit';

test.describe('Visits API | Create visit', () => {
  test.describe('POSITIVE', () => {
    test('Creates an OPEN visit with every field populated and persists it', {
      tag: [...VISIT_API_TAGS, '@POSITIVE', '@SMOKE'],
    }, async ({ visitsApi }) => {
      let payload!: VisitPayload;
      let created!: Visit;

      await test.step('Register a patient and an attending doctor', async () => {
        const patient = await visitsApi.registerPatient();
        const doctor = await visitsApi.registerPerson(['DOCTOR']);
        payload = buildVisit(patient._id, { type: 'EMERGENCY', attendingProfessionalId: doctor._id });
      });

      await test.step('Post the visit', async () => {
        const response = await visitsApi.create(payload);
        await expectStatus(response, 201);
        created = await readJson<Visit>(response);
      });

      await test.step('Response complies with the visit model and reflects the payload', async () => {
        expectVisitContract(created);
        expectVisitToMatchPayload(created, payload);
      });

      await test.step('A new visit starts OPEN without a closing timestamp (rule 4)', async () => {
        expectActiveVisit(created, 'OPEN');
      });

      await test.step('The visit is persisted and retrievable by ID', async () => {
        const persisted = await visitsApi.getVisit(created._id);
        expectVisitToMatchPayload(persisted, payload);
        expectActiveVisit(persisted, 'OPEN');
        expect(persisted.createdAt).toBe(created.createdAt);
      });
    });

    test('Creates a visit with only the required fields and defaults the admission date to server time', {
      tag: [...VISIT_API_TAGS, '@POSITIVE', '@BOUNDARY'],
    }, async ({ visitsApi }) => {
      let payload!: VisitPayload;
      let created!: Visit;

      await test.step('Post a payload with patient, type and chief complaint only', async () => {
        const patient = await visitsApi.registerPatient();
        payload = buildRequiredOnlyVisit(patient._id);
        created = await visitsApi.openVisit(payload);
      });

      await test.step('Response complies with the visit model', async () => {
        expectVisitContract(created);
        expectVisitToMatchPayload(created, payload);
        expectActiveVisit(created, 'OPEN');
      });

      await test.step('admissionDate is generated by the server at creation time', async () => {
        const drift = Math.abs(toEpoch(created.admissionDate) - toEpoch(created.createdAt));
        expect(drift, `admissionDate ${created.admissionDate} vs createdAt ${created.createdAt}`).toBeLessThanOrEqual(
          SAME_REQUEST_TOLERANCE_MS,
        );
      });

      await test.step('Optional fields are not invented by the API', async () => {
        expect(created.notes ?? '').toBe('');
        expect(referenceId(created.attendingProfessionalId)).toBeUndefined();
      });
    });

    for (const type of VISIT_TYPES) {
      test(`Creates a visit of type ${type}`, {
        tag: [...VISIT_API_TAGS, '@POSITIVE'],
      }, async ({ visitsApi }) => {
        await test.step(`Post a ${type} visit and read it back`, async () => {
          const patient = await visitsApi.registerPatient();
          const created = await visitsApi.openVisit(buildVisit(patient._id, { type }));
          expect(created.type).toBe(type);
          expect((await visitsApi.getVisit(created._id)).type).toBe(type);
        });
      });
    }

    const multiRolePatients: Array<{ roles: Role[]; label: string }> = [
      { roles: ['DOCTOR'], label: 'PATIENT and DOCTOR' },
      { roles: ['NURSE', 'NURSING_TECHNICIAN'], label: 'PATIENT, NURSE and NURSING_TECHNICIAN' },
      { roles: ['OTHER'], label: 'PATIENT and OTHER' },
    ];

    for (const { roles, label } of multiRolePatients) {
      test(`Accepts a patient who also holds other roles (${label})`, {
        tag: [...VISIT_API_TAGS, '@POSITIVE', '@EDGE'],
      }, async ({ visitsApi }) => {
        let patientId!: string;
        let created!: Visit;

        await test.step(`Register a person holding ${label}`, async () => {
          patientId = (await visitsApi.registerPatient(roles))._id;
        });

        await test.step('Open a visit for the multi-role patient', async () => {
          created = await visitsApi.openVisit(buildVisit(patientId));
          expect(referenceId(created.patientId)).toBe(patientId);
          expectActiveVisit(created, 'OPEN');
        });

        await test.step('The visit is listed for the patient', async () => {
          expect(idsOf(await visitsApi.listPatientVisits(patientId))).toEqual([created._id]);
        });
      });
    }

    test('Keeps the patient people record untouched when a visit is created (rule 16)', {
      tag: [...VISIT_API_TAGS, '@POSITIVE'],
    }, async ({ visitsApi, peopleApi }) => {
      let before!: Person;

      await test.step('Register a patient and snapshot the record', async () => {
        const patient = await visitsApi.registerPatient();
        before = await peopleApi.getPerson(patient._id);
      });

      await test.step('Open a visit for the patient', async () => {
        await visitsApi.openVisit(buildVisit(before._id));
      });

      await test.step('The people record is unchanged and not duplicated', async () => {
        expect(await peopleApi.getPerson(before._id)).toEqual(before);
        const all = await peopleApi.listAll();
        expect(all.filter((person: Person) => person.cpf === before.cpf)).toHaveLength(1);
      });
    });

    test('Preserves accented and non-ASCII characters in the chief complaint and notes', {
      tag: [...VISIT_API_TAGS, '@POSITIVE', '@EDGE'],
    }, async ({ visitsApi }) => {
      const chiefComplaint = `Dor no peito após exercício — coração acelerado ${Date.now()}`;
      const notes = 'Paciente relata náusea; pressão 14×9 mmHg; ñ alergias conhecidas';

      await test.step('Post and read back a visit with Unicode text', async () => {
        const patient = await visitsApi.registerPatient();
        const created = await visitsApi.openVisit(buildVisit(patient._id, { chiefComplaint, notes }));
        const persisted = await visitsApi.getVisit(created._id);
        expect(persisted.chiefComplaint).toBe(chiefComplaint);
        expect(persisted.notes).toBe(notes);
      });
    });

    test('Never lets the client choose the initial status or the closing timestamp', {
      tag: [...VISIT_API_TAGS, '@POSITIVE', '@EDGE'],
    }, async ({ visitsApi }) => {
      let patientId!: string;
      let response!: APIResponse;

      await test.step('Post a visit claiming to be COMPLETED with a closedAt value', async () => {
        patientId = (await visitsApi.registerPatient())._id;
        response = await visitsApi.create({
          ...buildVisit(patientId),
          status: 'COMPLETED',
          closedAt: new Date().toISOString(),
        });
        // Rejecting the server-managed fields or ignoring them are both acceptable.
        await expectStatus(response, [201, 400, 422]);
      });

      await test.step('Any persisted visit is OPEN and has no closing timestamp', async () => {
        for (const visit of await visitsApi.listVisits({ patientId })) {
          expectActiveVisit(visit, 'OPEN');
        }
      });
    });
  });

  test.describe('NEGATIVE', () => {
    for (const field of ['patientId', 'type', 'chiefComplaint'] as const) {
      test(`Rejects a visit without the required field "${field}"`, {
        tag: [...VISIT_API_TAGS, '@NEGATIVE'],
      }, async ({ visitsApi }) => {
        let patientId!: string;

        await test.step(`Post a payload missing "${field}"`, async () => {
          patientId = (await visitsApi.registerPatient())._id;
          const response = await visitsApi.create(buildVisitWithout(patientId, field));
          await expectApiError(response, [400, 422]);
        });

        await test.step('No visit is persisted for the patient', async () => {
          expect(await visitsApi.listPatientVisits(patientId)).toEqual([]);
        });
      });
    }

    const invalidValues: Array<{ field: keyof VisitPayload; value: unknown; label: string; tag: string }> = [
      { field: 'chiefComplaint', value: '', label: 'an empty chief complaint', tag: '@BOUNDARY' },
      { field: 'chiefComplaint', value: '   ', label: 'a whitespace-only chief complaint', tag: '@BOUNDARY' },
      { field: 'chiefComplaint', value: 42, label: 'a non-string chief complaint', tag: '@EDGE' },
      { field: 'type', value: 'SURGERY', label: 'an unsupported visit type', tag: '@NEGATIVE' },
      { field: 'type', value: '', label: 'an empty visit type', tag: '@BOUNDARY' },
      { field: 'type', value: ['OUTPATIENT'], label: 'a visit type sent as an array', tag: '@EDGE' },
      { field: 'admissionDate', value: 'not-a-date', label: 'an unparseable admission date', tag: '@NEGATIVE' },
      { field: 'admissionDate', value: '2024-13-01T10:00:00Z', label: 'an admission date with month 13', tag: '@BOUNDARY' },
      { field: 'admissionDate', value: '2024-02-30T10:00:00Z', label: 'a non-existent calendar admission date (Feb 30)', tag: '@EDGE' },
      { field: 'patientId', value: 12345, label: 'a numeric patient ID', tag: '@EDGE' },
    ];

    for (const { field, value, label, tag } of invalidValues) {
      test(`Rejects a visit with ${label}`, {
        tag: [...VISIT_API_TAGS, '@NEGATIVE', tag],
      }, async ({ visitsApi }) => {
        let patientId!: string;

        await test.step(`Post a payload with ${label}`, async () => {
          patientId = (await visitsApi.registerPatient())._id;
          const response = await visitsApi.create({ ...buildVisit(patientId), [field]: value });
          await expectApiError(response, [400, 422]);
        });

        await test.step('No visit is persisted for the patient', async () => {
          expect(await visitsApi.listPatientVisits(patientId)).toEqual([]);
        });
      });
    }

    for (const malformedId of MALFORMED_IDS) {
      test(`Rejects a malformed patient ID "${malformedId}"`, {
        tag: [...VISIT_API_TAGS, '@NEGATIVE'],
      }, async ({ visitsApi }) => {
        await test.step('Post a visit referencing a malformed patient ID', async () => {
          const response = await visitsApi.create(buildVisit(malformedId));
          await expectApiError(response, [400, 422], /patient/i);
        });
      });
    }

    test('Rejects a patient ID that does not belong to any person', {
      tag: [...VISIT_API_TAGS, '@NEGATIVE'],
    }, async ({ visitsApi }) => {
      await test.step('Post a visit referencing an unknown patient', async () => {
        const response = await visitsApi.create(buildVisit(UNKNOWN_OBJECT_ID));
        await expectApiError(response, [400, 404, 422], /patient/i);
      });

      await test.step('No visit is persisted for the unknown reference', async () => {
        expect(await visitsApi.listVisits({ patientId: UNKNOWN_OBJECT_ID })).toEqual([]);
      });
    });

    const nonPatientRoles: Array<{ roles: Role[]; label: string }> = [
      { roles: ['DOCTOR'], label: 'DOCTOR' },
      { roles: ['NURSE'], label: 'NURSE' },
      { roles: ['NURSING_TECHNICIAN'], label: 'NURSING_TECHNICIAN' },
      { roles: ['OTHER'], label: 'OTHER with a custom role' },
      { roles: ['DOCTOR', 'NURSE', 'NURSING_TECHNICIAN', 'OTHER'], label: 'every role except PATIENT' },
    ];

    for (const { roles, label } of nonPatientRoles) {
      test(`Rejects a person holding ${label} but not PATIENT as the visit patient (rule 1)`, {
        tag: [...VISIT_API_TAGS, '@NEGATIVE'],
      }, async ({ visitsApi, peopleApi }) => {
        let personId!: string;
        let before!: Person;

        await test.step(`Register a person holding ${label}`, async () => {
          personId = (await visitsApi.registerPerson(roles))._id;
          before = await peopleApi.getPerson(personId);
        });

        await test.step('Post a visit for the non-patient', async () => {
          const response = await visitsApi.create(buildVisit(personId));
          await expectApiError(response, [400, 422], /patient/i);
        });

        await test.step('No visit is persisted and the person record is unchanged', async () => {
          expect(await visitsApi.listVisits({ patientId: personId })).toEqual([]);
          expect(await peopleApi.getPerson(personId)).toEqual(before);
        });
      });
    }

    test('Rejects an attending professional ID that does not belong to any person', {
      tag: [...VISIT_API_TAGS, '@NEGATIVE'],
    }, async ({ visitsApi }) => {
      let patientId!: string;

      await test.step('Post a visit referencing an unknown professional', async () => {
        patientId = (await visitsApi.registerPatient())._id;
        const response = await visitsApi.create(buildVisit(patientId, { attendingProfessionalId: UNKNOWN_OBJECT_ID }));
        await expectApiError(response, [400, 404, 422], /professional/i);
      });

      await test.step('No visit is persisted for the patient', async () => {
        expect(await visitsApi.listPatientVisits(patientId)).toEqual([]);
      });
    });

    test('Rejects a malformed attending professional ID', {
      tag: [...VISIT_API_TAGS, '@NEGATIVE'],
    }, async ({ visitsApi }) => {
      let patientId!: string;

      await test.step('Post a visit referencing a malformed professional ID', async () => {
        patientId = (await visitsApi.registerPatient())._id;
        const response = await visitsApi.create(buildVisit(patientId, { attendingProfessionalId: 'not-an-object-id' }));
        await expectApiError(response, [400, 422], /professional/i);
      });

      await test.step('No visit is persisted for the patient', async () => {
        expect(await visitsApi.listPatientVisits(patientId)).toEqual([]);
      });
    });

    test('Rejects a person who only holds the PATIENT role as attending professional', {
      tag: [...VISIT_API_TAGS, '@NEGATIVE', '@CONTRACT-ASSUMPTION'],
    }, async ({ visitsApi }) => {
      let patientId!: string;

      await test.step('Post a visit whose attending professional is another patient', async () => {
        patientId = (await visitsApi.registerPatient())._id;
        const otherPatient = await visitsApi.registerPatient();
        const response = await visitsApi.create(buildVisit(patientId, { attendingProfessionalId: otherPatient._id }));
        await expectApiError(response, [400, 422], /professional/i);
      });

      await test.step('No visit is persisted for the patient', async () => {
        expect(await visitsApi.listPatientVisits(patientId)).toEqual([]);
      });
    });

    test('Rejects a malformed JSON body with a JSON error response', {
      tag: [...VISIT_API_TAGS, '@NEGATIVE', '@EDGE'],
    }, async ({ visitsApi }) => {
      // Guard: Express parses JSON bodies before routing, so a malformed body gets the
      // global JSON 400 even on unmounted URLs. Prove the endpoint exists first.
      await test.step('The create endpoint is mounted and validates a well-formed empty object', async () => {
        await expectApiError(await visitsApi.create({}), [400, 422]);
      });

      await test.step('Post a syntactically invalid JSON document', async () => {
        const response = await visitsApi.createRaw('{"patientId": "abc", "type": ');
        await expectApiError(response, 400);
      });
    });

    test('Rejects a JSON array body instead of a visit object', {
      tag: [...VISIT_API_TAGS, '@NEGATIVE', '@EDGE'],
    }, async ({ visitsApi }) => {
      let patientId!: string;

      await test.step('Post an array wrapping a valid visit', async () => {
        patientId = (await visitsApi.registerPatient())._id;
        const response = await visitsApi.create([buildVisit(patientId)]);
        await expectApiError(response, [400, 422]);
      });

      await test.step('No visit is persisted for the patient', async () => {
        expect(idsOf(await visitsApi.listPatientVisits(patientId))).toEqual([]);
      });
    });
  });
});
